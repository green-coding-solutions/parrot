#!/usr/bin/env python3
"""Write the synthetic macros and the usage scenario of the replay overhead benchmark.

The benchmark measures what replay.py itself costs, apart from the application
it drives. Every condition runs against xlogo, which draws one static picture
and reacts to nothing, so whatever a condition costs above the idle control is
the cost of replaying it. See README.md next to this file for the design.

One macro per condition, each replayed as a whole file in a flow step of its
own, so every condition is a GMT phase:

    start.parrot              hidden step: start xlogo and check it once
    idle.parrot               the control: no input events
    mousemove-<R>hz.parrot    R pointer moves per second, one per rate
    keypress-a-<R>hz.parrot   R presses of the `a` key per second, one per rate
    keypress-shift-<R>hz.parrot
                              R presses of Shift_L per second, one per rate
    checks.parrot             screenshot checks, evenly spaced

Every condition lasts the same recorded time, --duration seconds, between an
opening and a closing `log` line. Rerun after changing a parameter. --check
writes nothing and exits 1 when a file is missing or out of date.

    ./generate.py
    ./generate.py --duration 120 --move-rates 10,100 --key-rates 10 --checks 24
    ./generate.py --check
"""

from __future__ import annotations

import argparse
import sys
import textwrap
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent.parent
CONTAINER_REPO = "/tmp/repo"
CONTAINER_HERE = f"{CONTAINER_REPO}/{HERE.relative_to(REPO).as_posix()}"

# The same window matcher as applications/demos/xlogo/xlogo.parrot. Every file
# carries it, so replay.py finds the xlogo that start.parrot left running.
METADATA = ["startcommand = xlogo", "windowtitle = xlogo", "windowclass = xlogo"]

# The reference screenshot, xlogo at 1439x877, the size usage_scenario.yml pins
# the window to. replay.py resolves it against applications/demos/.
#
# It is NOT applications/demos/xlogo/xlogo-check-001.png, although that one has
# the same size. xlogo 7.7+11build3 in the current image draws the logo a few
# pixels off that image along every edge, 2.5 % of the window, which is an RMSE
# of 0.159 against a limit of 0.2. That passes, but it would let through almost
# any change to xlogo, and the checks phase is also what confirms that the key
# phases left xlogo alone. This one was captured from the scenario's own setup
# (apt-snapshot.sh, x11-apps=7.7+11build3, start.parrot) and matches at 0.
CHECK_REF = "overhead/overhead-check-001.png"

# Two points well inside the pinned xlogo window. The pointer alternates between
# them, so every event is a real move and none leaves the window, which would
# add Enter and Leave events to some moves and not to others.
POINT_A = (560, 380)
POINT_B = (880, 500)

# The key of the plain key-press conditions. xlogo's app-defaults bind exactly
# two keys, `q` and `Escape`, both to quit(), and xlogo has no other key handling.
# Pressing either would end every later phase. `a` does nothing at all.
KEY_PLAIN = "a"
# The key of the modifier condition. Through the xtest injector a modifier takes
# its own branch, see XTestInjector._send_modifiers in replay.py.
KEY_MODIFIER = "Shift_L"
# How long a key is held. The median keydown to keyup gap in the committed
# recordings is 11.6 ms for plain keys and 11.9 ms for modifiers.
KEY_HOLD = 0.012

GENERATED = "# GENERATED by generate.py. Do not edit. Change the generator and rerun it."


def wait(seconds: float) -> str:
    return f"wait {seconds:.6f}"


def parrot_file(paragraphs: list[str], events: list[str]) -> str:
    """Return a .parrot file: the header, *paragraphs* as a comment, the metadata and *events*."""
    lines = ["# Parrot recording v2", GENERATED]
    for paragraph in paragraphs:
        lines.append("#")
        lines += [f"# {line}" for line in textwrap.wrap(paragraph, width=76)]
    lines += [""] + METADATA + [""] + events
    return "\n".join(lines) + "\n"


def start_macro() -> str:
    return parrot_file(
        [
            "Replay overhead benchmark, hidden step: start xlogo.",
            "Uses replay.py's own path for launching the app, waiting for its window, "
            "positioning and focusing it, so the app start is in a hidden step and in "
            "no measured phase. The check confirms xlogo is drawn at the reference "
            "geometry before anything is measured, which every condition relies on.",
        ],
        [
            wait(2.0),
            "log xlogo ready: started, positioned and matching its reference screenshot",
            f"check {CHECK_REF}",
        ],
    )


def idle_macro(duration: float) -> str:
    return parrot_file(
        [
            "Replay overhead benchmark, measured phase: the idle control.",
            f"{duration:g} s without a single event, as long as every other condition. "
            "It holds everything the other phases hold except their events: xlogo, "
            "the X server, and replay.py starting up and sleeping. What a condition "
            "costs above this phase is what its events cost.",
            "The closing `log` is the event the wait is slept before. replay.py "
            "applies a `wait` to the NEXT event and drops a trailing one.",
        ],
        [
            f"log Idle: no input events for {duration:g} s",
            wait(duration),
            f"log Idle complete: {duration:g} s without input",
        ],
    )


def mousemove_macro(duration: float, rate: int) -> str:
    count = round(duration * rate)
    interval = 1.0 / rate
    pairs, odd = divmod(count, 2)
    move_a = f"mousemove {POINT_A[0]} {POINT_A[1]}"
    move_b = f"mousemove {POINT_B[0]} {POINT_B[1]}"
    label = f"Mousemove {rate} Hz"
    events = [f"log {label}: {count} pointer moves, {interval * 1000:g} ms apart, for {duration:g} s"]
    if pairs:
        events += ["label move", wait(interval), move_a, wait(interval), move_b, f"loop move {pairs}"]
    if odd:
        events += [wait(interval), move_a]
    events.append(f"log {label} complete: {count} pointer moves in {duration:g} s of recorded time")
    return parrot_file(
        [
            f"Replay overhead benchmark, measured phase: {rate} pointer moves per second.",
            f"{count} mousemove events, {interval * 1000:g} ms apart, for {duration:g} s. "
            f"The pointer alternates between {POINT_A[0]},{POINT_A[1]} and "
            f"{POINT_B[0]},{POINT_B[1]}, both inside the xlogo window. xlogo draws "
            "nothing on pointer motion, so the application's share of a move is nil "
            "and the X server's share is the same for both injectors. The rest is the "
            "injector.",
            "The wait comes FIRST inside the loop body. `loop` clears the pending wait "
            "when it jumps, so a wait written just before the `loop` line would be "
            "dropped on every iteration but the last.",
        ],
        events,
    )


def keypress_macro(duration: float, rate: int, key: str, label: str) -> str:
    count = round(duration * rate)
    period = 1.0 / rate
    events = [
        f"log {label}: {count} presses of the {key} key, one every {period * 1000:g} ms, "
        f"held {KEY_HOLD * 1000:g} ms, for {duration:g} s",
        "label press", wait(period - KEY_HOLD), f"keydown {key}", wait(KEY_HOLD), f"keyup {key}",
        f"loop press {count}",
        f"log {label} complete: {count} presses in {duration:g} s of recorded time",
    ]
    if key == KEY_PLAIN:
        why = (f"xlogo's app-defaults bind only `q` and `Escape`, both to quit, so `{key}` "
               "changes nothing. If it did, the screenshot checks phase that runs after "
               "this one would fail.")
    else:
        why = (f"{key} is a modifier. The xtest injector sends it the way xdotool does, "
               "the first keycode of its modifier and then the key itself, which here is "
               "the same keycode. xlogo binds no modifier combination, and the screenshot "
               "checks phase that runs after this one would fail if it changed anything.")
    return parrot_file(
        [
            f"Replay overhead benchmark, measured phase: {rate} presses of the {key} key per second.",
            f"{count} presses, one every {period * 1000:g} ms, for {duration:g} s. Each "
            f"press is a keydown and a keyup {KEY_HOLD * 1000:g} ms later, about as long "
            "as a key is held in the recordings. Key events are most of what the "
            "recordings replay, and with the xdotool injector every one of them is a "
            "process that also sleeps 12 ms after its event, so a press costs two "
            "process starts and 24 ms of sleep that the recording does not have.",
            why,
            "The wait comes FIRST inside the loop body. `loop` clears the pending wait "
            "when it jumps, so a wait written just before the `loop` line would be "
            "dropped on every iteration but the last.",
        ],
        events,
    )


def checks_macro(duration: float, checks: int) -> str:
    interval = duration / checks
    events = [f"log Screenshot checks: {checks} checks, one every {interval:g} s, for {duration:g} s"]
    for _ in range(checks):
        events += [wait(interval), f"check {CHECK_REF}"]
    events.append(f"log Screenshot checks complete: {checks} checks in {duration:g} s of recorded time")
    return parrot_file(
        [
            "Replay overhead benchmark, measured phase: screenshot checks.",
            f"{checks} checks, one every {interval:g} s, for {duration:g} s, and no input "
            "events. Each one costs what a checkpoint in a recording costs. "
            "check-image.sh grabs the window with ImageMagick's `import` and compares "
            "it with `compare -metric RMSE`. xlogo does not change, so every check "
            "compares against the same reference and has to pass.",
        ],
        events,
    )


def scenario(phases: list[tuple[str, str]]) -> str:
    """Return usage_scenario.yml for the measured *phases*, (flow name, macro file) each."""
    head = f"""# GENERATED by applications/demos/overhead/generate.py. Do not edit. Change the
# generator and rerun it.
#
# Measures what replay.py itself costs. The same synthetic macros run against a
# static xlogo, with the injector and the timing mode chosen per run. See
# applications/demos/overhead/README.md for the experiment design.
#
# TWO VARIABLES, BOTH REQUIRED. GMT refuses to start a run, at parse time, when
# either is missing:
#
#   __GMT_VAR_INJECTOR__   xdotool or xtest         becomes REPLAY_INJECTOR
#   __GMT_VAR_TIMING__     relative or absolute     becomes REPLAY_TIMING
#
# xdotool with relative is what every other Parrot scenario runs, the "before".
#
# RUN IT WITH:
#
#   cd /home/didi/code/green-metrics-tool && venv/bin/python runner.py \\
#     --uri /home/didi/code/parrot \\
#     --filename applications/demos/overhead/usage_scenario.yml \\
#     --variable __GMT_VAR_INJECTOR__=xtest --variable __GMT_VAR_TIMING__=absolute \\
#     --dev-no-system-checks=check_ssh_session
#
# Every flow step calls {CONTAINER_REPO}/replay.py, the copy in the mounted
# repository, and not /usr/local/bin/replay.py from the image. That copy imports
# helpers.py and timed_xmacro.py from its own folder, so the branch under test
# runs without rebuilding the image. check-image.sh, position-window.sh and
# freeze-window-size.py still come from the image.
name: "Parrot replay overhead (__GMT_VAR_INJECTOR__, __GMT_VAR_TIMING__)"
author: Didi <didi@green-coding.io>
description: "Replays synthetic macros against a static xlogo to measure the replay harness itself, injector __GMT_VAR_INJECTOR__, timing __GMT_VAR_TIMING__"

services:
  window-container:
    image: ribalba/xwindow-server
    # ports:
    #   - "6080:6080" # noVNC (open in browser)
    #   - "5900:5900" # raw VNC
    environment:
      # DEBUG: 1
      RESOLUTION: 1440x900
      # position-window.sh reads these. replay.py only fills them in from a
      # recording's first check image, and only start.parrot and checks.parrot
      # have one, so without them position-window.sh would fall back to its demo
      # defaults and resize xlogo to 1400x857 at 20,20 in every other phase.
      # 1439x877 at 0,0 is what applications/demos/xlogo was recorded at.
      WINDOW_X: 0
      WINDOW_Y: 0
      WINDOW_WIDTH: 1439
      WINDOW_HEIGHT: 877
      # Read by replay.py, see INJECTORS in replay.py and TIMINGS in timed_xmacro.py.
      REPLAY_INJECTOR: __GMT_VAR_INJECTOR__
      REPLAY_TIMING: __GMT_VAR_TIMING__

    setup-commands:
      # First, before anything calls apt, freeze the Ubuntu archive at the
      # sweep commit, so every machine and repetition installs the same packages.
      - command: bash {CONTAINER_REPO}/applications/common/apt-snapshot.sh
      - command: apt-get install -y --no-install-recommends x11-apps=7.7+11build3
      - command: bash /usr/local/bin/entrypoint.sh

flow:
  # The app is started here, in a hidden step, so no app start-up is inside a
  # measured phase.
  - name: Start xlogo
    container: window-container
    hidden: true
    commands:
      - type: console
        command: python3 {CONTAINER_REPO}/replay.py {CONTAINER_HERE}/start.parrot
"""
    steps = []
    for name, macro in phases:
        steps.append(
            f"""  - name: {name}
    container: window-container
    commands:
      - type: console
        command: python3 {CONTAINER_REPO}/replay.py {CONTAINER_HERE}/{macro}
        read-notes-stdout: true
"""
        )
    return head + "".join(steps)


def render(duration: float, move_rates: list[int], key_rates: list[int],
           shift_rates: list[int], checks: int) -> dict[str, str]:
    """Return {file name: content} for every file this script writes."""
    files = {"start.parrot": start_macro(), "idle.parrot": idle_macro(duration)}
    phases = [("Idle", "idle.parrot")]
    for rate in move_rates:
        name = f"mousemove-{rate}hz.parrot"
        files[name] = mousemove_macro(duration, rate)
        phases.append((f"Mousemove {rate} Hz", name))
    for rate in key_rates:
        name = f"keypress-a-{rate}hz.parrot"
        files[name] = keypress_macro(duration, rate, KEY_PLAIN, f"Key presses {rate} Hz")
        phases.append((f"Key presses {rate} Hz", name))
    for rate in shift_rates:
        name = f"keypress-shift-{rate}hz.parrot"
        files[name] = keypress_macro(duration, rate, KEY_MODIFIER, f"Shift presses {rate} Hz")
        phases.append((f"Shift presses {rate} Hz", name))
    # Last, so that it also confirms the key phases left xlogo as it was.
    files["checks.parrot"] = checks_macro(duration, checks)
    phases.append(("Screenshot checks", "checks.parrot"))
    files["usage_scenario.yml"] = scenario(phases)
    return files


def positive_rates(raw: str) -> list[int]:
    try:
        rates = [int(part) for part in raw.split(",") if part.strip()]
    except ValueError:
        raise argparse.ArgumentTypeError(f"not a comma-separated list of integers: {raw!r}") from None
    if any(rate <= 0 for rate in rates) or len(set(rates)) != len(rates):
        raise argparse.ArgumentTypeError(f"rates must be distinct and > 0: {raw!r}")
    return rates


def key_rates(raw: str) -> list[int]:
    rates = positive_rates(raw)
    if any(1.0 / rate <= KEY_HOLD for rate in rates):
        raise argparse.ArgumentTypeError(
            f"a key is held {KEY_HOLD * 1000:g} ms, so a press rate must stay below "
            f"{1.0 / KEY_HOLD:g} per second: {raw!r}")
    return rates


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--duration", type=float, default=60.0,
                        help="recorded seconds of every condition (default: 60)")
    parser.add_argument("--move-rates", type=positive_rates, default=[10, 50, 200],
                        help="mousemove rates in events per second, comma-separated, "
                             "empty for none (default: 10,50,200)")
    parser.add_argument("--key-rates", type=key_rates, default=[5, 20],
                        help=f"presses of {KEY_PLAIN!r} per second, comma-separated, "
                             "empty for none (default: 5,20)")
    parser.add_argument("--shift-rates", type=key_rates, default=[5],
                        help=f"presses of {KEY_MODIFIER} per second, comma-separated, "
                             "empty for none (default: 5)")
    parser.add_argument("--checks", type=int, default=12,
                        help="screenshot checks in the checks condition (default: 12)")
    parser.add_argument("--check", action="store_true",
                        help="write nothing and exit 1 if any file is missing or out of date")
    args = parser.parse_args(argv)
    if args.duration <= 0 or args.checks <= 0:
        parser.error("--duration and --checks must be > 0")

    failed = False
    files = render(args.duration, args.move_rates, args.key_rates, args.shift_rates, args.checks)
    for name, content in files.items():
        target = HERE / name
        current = target.read_text(encoding="utf-8") if target.exists() else None
        if current == content:
            print(f"up to date  {name}")
        elif args.check:
            print(f"{'STALE' if current is not None else 'MISSING'}  {name}", file=sys.stderr)
            failed = True
        else:
            target.write_text(content, encoding="utf-8")
            print(f"wrote       {name}")
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
